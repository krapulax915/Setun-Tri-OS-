"""M8 acceptance: loader + coreutils — a scripted shell session.

A single scripted session exercises the whole M8 surface on a 2228-block
disk: help / mkdir / ed / ls / cat / run-txe (loader) / ps / tstat /
kill / cp / rm / cat-again / pipe / halt.  The kernel is assembled from
source (no stale artifacts), the staged hello/spin programs are compiled
from user/*.asm, and the session must end with a clean power-off, no
trap reports, and the expected command replies.

Host-side memory checks back the visible output: after `cp docs/notes
docs/notes2` the namespace table (NTS, D-047) holds an entry NAMED
"docs/notes2" (the 25-char command line proves the shell line buffer
holds more than 24 chars, D-049), and after `rm docs/notes2` its entry
is freed again.
"""
import os
import sys
import unittest

TOOLS = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tools")
sys.path.insert(0, TOOLS)

import triasm                        # noqa: E402
import trild                        # noqa: E402
import trimkfs                       # noqa: E402
import pack as packmod               # noqa: E402
from tvm.machine import Machine      # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NBLOCKS = 2228                       # FS_BASE + 2200 fs blocks (D-042)

# kernel.asm memory layout (kept in sync by hand; kernel boots with these)
M8WORK = 1417 * 729
NTS = M8WORK + 12                    # name table: 48 x 30-tryte entries
NTE = 30                             # [index word, flags word, name <= 24]

SCRIPT = ("help\n"
          "mkdir docs\n"
          "ed docs/notes\n"
          "hello ternary world\n"
          ".\n"
          "ls\n"
          "cat docs/notes\n"
          "exec hello\n"
          "ps\n"
          "tstat 1\n"
          "kill 99\n"
          "cp docs/notes docs/notes2\n"    # 25 chars — needs the D-049 LBUF
          "cat docs/notes2\n"
          "rm docs/notes2\n"
          "cat docs/notes2\n"
          "pipe\n"
          "halt\n")


def build_disk():
    rom = triasm.assemble_file(os.path.join(REPO, "boot", "rom.asm"), org=0, rom=True)
    boot = triasm.assemble_file(os.path.join(REPO, "boot", "boot.asm"))
    kernel = triasm.assemble_file(os.path.join(REPO, "kernel", "kernel.asm"))
    # the staged hello/spin programs are embedded in kernel.asm via
    # hello_txedata.asm (regenerated by tools/mk.py assemble)
    txe = trild.link_txe([kernel])
    return rom.rom_bytes, trimkfs.build_boot_image(
        boot.spans()[0][1], packmod.unpack_trytes(txe), nblocks=NBLOCKS)


def run_session(rom_bytes, disk_bytes, max_steps=120_000_000):
    m = Machine(rom_bytes=rom_bytes, disk_bytes=disk_bytes)
    m.feed_stdin(SCRIPT)
    code = m.run(max_steps=max_steps)
    text = m.output_text()
    i = text.index("$ ")                 # skip the boot log
    return m, code, text, text[i:]


def read_name(m, entry):
    """Decode the NUL-terminated name field of NTS entry `entry`."""
    base = NTS + entry * NTE + 6
    out = []
    for j in range(24):
        t = m.cpu.mem.read_tryte(base + j)
        if t == 0:
            break
        out.append(chr(t))
    return "".join(out)


def read_flags(m, entry):
    return m.cpu.mem.read_word(NTS + entry * NTE + 3)


class TestM8Session(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.rom, cls.disk = build_disk()
        cls.m, cls.code, cls.full, cls.text = run_session(cls.rom, cls.disk)

    def test_clean_poweroff_and_no_traps(self):
        self.assertEqual(self.code, 0)
        self.assertTrue(self.m.powered_off)
        # boot self-tests deliberately trap (illegal/div0 resume checks), so
        # the no-trap assertion covers the shell session only
        self.assertNotIn("trap cause", self.text)
        self.assertNotIn("self-test: FAIL", self.full)

    def test_builtins_and_staging(self):
        self.assertIn("builtins: help ver echo", self.text)
        self.assertIn("m8: hello program staged", self.full)

    def test_fs_ops(self):
        self.assertIn("mkdir ok", self.text)
        self.assertIn("ed: saved", self.text)
        self.assertIn("hello ternary world", self.text)   # cat docs/notes
        self.assertIn("docs/notes", self.text)            # ls
        self.assertIn("cp ok", self.text)
        # the copy is readable under the NEW name
        i = self.text.index("cat docs/notes2")
        j = self.text.index("rm docs/notes2")
        self.assertIn("hello ternary world", self.text[i:j])
        self.assertIn("rm ok", self.text)
        # after rm the name is gone again
        k = self.text.rindex("cat docs/notes2")
        self.assertIn("no such name", self.text[k:])

    def test_proc_and_pipe_ops(self):
        self.assertIn("exec: tid 6", self.text)
        self.assertIn("kill refused", self.text)
        self.assertIn("ternary pipe ok", self.text)
        # ps lists the running threads (interleaved with hello's output —
        # two threads share the console, acceptable in v0.1)
        for row in ("0 1 0", "6 0 0"):
            self.assertIn(row, self.text)

    def test_namespace_table_host_side(self):
        # entry 3 = docs/notes (created by ed), still occupied
        self.assertEqual(read_name(self.m, 3), "docs/notes")
        self.assertNotEqual(read_flags(self.m, 3), 0)
        # entry 4 = the cp target: named with the DST name (this exact
        # check failed before D-048/D-049) and freed again by rm
        self.assertEqual(read_name(self.m, 4), "docs/notes2")
        self.assertEqual(read_flags(self.m, 4), 0)


if __name__ == "__main__":
    unittest.main()
